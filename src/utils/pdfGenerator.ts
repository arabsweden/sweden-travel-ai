import { jsPDF } from 'jspdf';
import { Language } from '../types';

export interface PDFItineraryData {
  title: string;
  departureCountry: string;
  startDate: string;
  endDate: string;
  budget: string;
  travelStyle: string;
  adults: number;
  children: number;
  preferredCities: string[];
  itineraryDays: Array<{
    day: number;
    title: string;
    description: string;
    activities: Array<{
      time: string;
      title: string;
      location?: string;
      description: string;
      cost?: string;
    }>;
  }>;
  estimatedCosts?: Record<string, string | number>;
}

/**
 * Sanitizes Swedish or special Latin/Arabic characters for PDF safe rendering 
 * and fallback representation if standard Helvetica fonts are used.
 */
function sanitizeText(text: string, language: Language): string {
  if (!text) return '';
  
  // Basic replacement for any weird directional symbols or characters
  let clean = text.replace(/[\u200B-\u200D\uFEFF]/g, '');
  
  // If language is Arabic, standard PDF viewer with basic Helvetica cannot display Arabic glyphs.
  // We can write transliterations or an explanation, but the actual content contains English values generated by Gemini as well.
  // To prevent rendering boxes/question marks, we will replace or handle Arabic gracefully 
  // by using its English/Latin representation if possible, or keeping standard clean text.
  return clean;
}

export function generateItineraryPDF(data: PDFItineraryData, language: Language): void {
  // Create a portrait, A4, millimeters-based PDF
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageW = doc.internal.pageSize.getWidth(); // 210
  const pageH = doc.internal.pageSize.getHeight(); // 297
  const margin = 15;
  const contentW = pageW - (margin * 2); // 180

  let y = 15;

  // Colors based on Sweden brand (Scandi Blue / Scandi Yellow / Dark Charcoal)
  const scandiBlue = { r: 0, g: 75, b: 135 }; // #004B87
  const scandiYellow = { r: 255, g: 221, b: 0 }; // #FFDD00
  const darkCharcoal = { r: 30, g: 41, b: 59 }; // #1E293B
  const slateMuted = { r: 100, g: 116, b: 139 }; // #64748B
  const lightBg = { r: 241, g: 245, b: 249 }; // #F1F5F9
  const borderGrey = { r: 226, g: 232, b: 240 }; // #E2E8F0

  // 1. Draw Page Background Decoration (Clean Swedish minimalist touch)
  const drawPageBorder = () => {
    doc.setDrawColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
    doc.setLineWidth(0.7);
    // Draw top thin brand accent line
    doc.line(0, 0, pageW, 0);
    doc.setDrawColor(scandiYellow.r, scandiYellow.g, scandiYellow.b);
    doc.line(0, 1, pageW, 1);
  };

  // Helper to draw clean footers
  const drawFooter = (pageNum: number, totalPages: number) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(slateMuted.r, slateMuted.g, slateMuted.b);
    
    // Line above footer
    doc.setDrawColor(borderGrey.r, borderGrey.g, borderGrey.b);
    doc.setLineWidth(0.3);
    doc.line(margin, pageH - 12, pageW - margin, pageH - 12);
    
    const footerText = language === 'ar' 
      ? 'تم التوليد بواسطة السويد الذكي للسفر • رحلة سعيدة!' 
      : language === 'sv' 
      ? 'Genererad av Sverige Reseplanerare • Trevlig resa!' 
      : 'Generated by Sweden Travel AI Assistant • Trevlig resa!';
      
    doc.text(footerText, margin, pageH - 8);
    
    const pageText = `${pageNum} / ${totalPages}`;
    doc.text(pageText, pageW - margin - doc.getTextWidth(pageText), pageH - 8);
  };

  // Helper to safely add text with autowrap and check for page overflow
  const addWrappedText = (text: string, fontSize: number, style: 'normal' | 'bold' | 'italic', color: { r: number, g: number, b: number }, spacingAfter: number): void => {
    doc.setFont('helvetica', style);
    doc.setFontSize(fontSize);
    doc.setTextColor(color.r, color.g, color.b);

    const lines = doc.splitTextToSize(sanitizeText(text, language), contentW);
    const lineHeight = fontSize * 0.3527 * 1.35; // pt to mm with spacing factor
    
    for (const line of lines) {
      if (y + lineHeight > pageH - 18) {
        doc.addPage();
        drawPageBorder();
        y = 20;
      }
      doc.text(line, margin, y);
      y += lineHeight;
    }
    y += spacingAfter;
  };

  // Helper to check and handle page overflows
  const ensureSpace = (neededHeight: number): void => {
    if (y + neededHeight > pageH - 18) {
      doc.addPage();
      drawPageBorder();
      y = 20;
    }
  };

  // --- BEGIN DOCUMENT DRAWING ---
  drawPageBorder();

  // Draw Header Banner
  doc.setFillColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
  doc.rect(margin, y, contentW, 28, 'F');

  // Yellow accent ribbon on left side of header banner
  doc.setFillColor(scandiYellow.r, scandiYellow.g, scandiYellow.b);
  doc.rect(margin, y, 4, 28, 'F');

  // Title Text
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text(sanitizeText(data.title || 'Sweden Travel Itinerary', language), margin + 8, y + 10);

  // Subtitle Text
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(230, 240, 255);
  const subtitleStr = language === 'ar' 
    ? 'مخطط رحلتك المخصص بالذكاء الاصطناعي إلى السويد' 
    : language === 'sv' 
    ? 'Din AI-genererade personliga resplan till Sverige' 
    : 'Your Personalized AI-Generated Sweden Travel Itinerary';
  doc.text(subtitleStr, margin + 8, y + 16);

  // Logo Badge on top right of banner
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(scandiYellow.r, scandiYellow.g, scandiYellow.b);
  doc.text('SVERIGE', pageW - margin - 32, y + 11);
  doc.setFontSize(7);
  doc.setTextColor(255, 255, 255);
  doc.text('TRAVEL PLANNER', pageW - margin - 32, y + 15);

  y += 34;

  // Facts Box (Gray rounded-like rectangle background)
  ensureSpace(26);
  doc.setFillColor(lightBg.r, lightBg.g, lightBg.b);
  doc.setDrawColor(borderGrey.r, borderGrey.g, borderGrey.b);
  doc.setLineWidth(0.3);
  doc.rect(margin, y, contentW, 22, 'FD');

  // Grid labels and values inside Facts Box
  const colW = contentW / 4;
  const labelY = y + 6;
  const valueY = y + 13;

  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(slateMuted.r, slateMuted.g, slateMuted.b);
  
  // Col 1: Departure
  doc.text(language === 'ar' ? 'المغادرة من' : language === 'sv' ? 'AVRESA FRÅN' : 'DEPARTING FROM', margin + 6, labelY);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
  doc.text(sanitizeText(data.departureCountry, language), margin + 6, valueY);

  // Col 2: Dates
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(slateMuted.r, slateMuted.g, slateMuted.b);
  doc.text(language === 'ar' ? 'التواريخ والمدة' : language === 'sv' ? 'RESEDATUM' : 'TRAVEL DATES', margin + colW + 4, labelY);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
  doc.text(`${data.startDate} to ${data.endDate}`, margin + colW + 4, valueY);

  // Col 3: Travelers
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(slateMuted.r, slateMuted.g, slateMuted.b);
  doc.text(language === 'ar' ? 'المسافرين' : language === 'sv' ? 'RESENÄRER' : 'TRAVELERS', margin + (colW * 2) + 4, labelY);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
  const travelerText = `${data.adults} Adults` + (data.children > 0 ? `, ${data.children} Children` : '');
  doc.text(travelerText, margin + (colW * 2) + 4, valueY);

  // Col 4: Budget / Style
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(slateMuted.r, slateMuted.g, slateMuted.b);
  doc.text(language === 'ar' ? 'الميزانية والنمط' : language === 'sv' ? 'BUDGET & STIL' : 'BUDGET & STYLE', margin + (colW * 3) + 4, labelY);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
  doc.text(`${data.travelStyle} (${data.budget})`, margin + (colW * 3) + 4, valueY);

  y += 28;

  // Preferred Cities Row
  if (data.preferredCities && data.preferredCities.length > 0) {
    ensureSpace(8);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
    doc.text((language === 'ar' ? 'المدن المستهدفة: ' : language === 'sv' ? 'Besökta städer: ' : 'Planned Destinations: ') + data.preferredCities.join(', '), margin, y);
    y += 8;
  }

  // --- 2. ESTIMATED COST BREAKDOWN TABLE ---
  if (data.estimatedCosts && Object.keys(data.estimatedCosts).length > 0) {
    ensureSpace(45);
    
    // Header for cost breakdown
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
    doc.text(language === 'ar' ? 'تقدير تكاليف الرحلة (كرونة سويدية)' : language === 'sv' ? 'Beräknad Kostnadskalkyl (SEK)' : 'Estimated Cost Breakdown (SEK)', margin, y);
    
    // Thin line
    doc.setDrawColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
    doc.setLineWidth(0.4);
    doc.line(margin, y + 2, pageW - margin, y + 2);
    
    y += 6;

    // Draw cost rows
    const costEntries = Object.entries(data.estimatedCosts);
    doc.setFontSize(9);
    
    for (const [category, cost] of costEntries) {
      if (category === 'total') continue; // Print total at the end
      
      ensureSpace(6);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
      // Capitalize first letter of category
      const displayCategory = category.charAt(0).toUpperCase() + category.slice(1);
      doc.text(displayCategory, margin + 4, y);
      
      doc.setFont('helvetica', 'bold');
      const costStr = `${cost} SEK`;
      doc.text(costStr, pageW - margin - 20 - doc.getTextWidth(costStr), y);
      
      // Light separator line
      doc.setDrawColor(borderGrey.r, borderGrey.g, borderGrey.b);
      doc.setLineWidth(0.15);
      doc.line(margin, y + 1.5, pageW - margin, y + 1.5);
      
      y += 5.5;
    }

    // Print Total Budget row
    ensureSpace(10);
    doc.setFillColor(lightBg.r, lightBg.g, lightBg.b);
    doc.rect(margin, y, contentW, 8, 'F');
    
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
    doc.text(language === 'ar' ? 'الميزانية الإجمالية المقدرة' : language === 'sv' ? 'Total beräknad budget' : 'Total Estimated Budget', margin + 4, y + 5.5);
    
    const totalCostStr = `${data.estimatedCosts.total || 'N/A'} SEK`;
    doc.text(totalCostStr, pageW - margin - 20 - doc.getTextWidth(totalCostStr), y + 5.5);
    
    y += 14;
  }

  // --- 3. DETAILED DAILY ITINERARY ---
  ensureSpace(20);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
  doc.text(language === 'ar' ? 'تفاصيل المخطط اليومي' : language === 'sv' ? 'Detaljerat Dagsprogram' : 'Detailed Daily Itinerary', margin, y);
  
  // Accent underline
  doc.setDrawColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
  doc.setLineWidth(0.5);
  doc.line(margin, y + 2, margin + 35, y + 2);
  
  y += 9;

  // Loop through days
  if (data.itineraryDays && data.itineraryDays.length > 0) {
    for (const day of data.itineraryDays) {
      ensureSpace(35); // Require a safe block size for the day header + initial activity
      
      // Day Header box (Blue accent left bar)
      doc.setFillColor(lightBg.r, lightBg.g, lightBg.b);
      doc.rect(margin, y, contentW, 10, 'F');
      
      doc.setFillColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
      doc.rect(margin, y, 3, 10, 'F');

      // Day X text
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10.5);
      doc.setTextColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
      const dayNumStr = language === 'ar' ? `اليوم ${day.day}: ` : language === 'sv' ? `DAG ${day.day}: ` : `DAY ${day.day}: `;
      doc.text(dayNumStr, margin + 6, y + 6.5);

      // Day Title text
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10.5);
      doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
      doc.text(sanitizeText(day.title, language), margin + 6 + doc.getTextWidth(dayNumStr), y + 6.5);
      
      y += 14;

      // Day Description paragraph (italic)
      if (day.description) {
        addWrappedText(day.description, 9, 'italic', slateMuted, 4);
      }

      // Loop activities
      if (day.activities && day.activities.length > 0) {
        for (const act of day.activities) {
          ensureSpace(22); // Minimum activity block height

          // Draw a small left timeline indicator bar for the activity
          doc.setDrawColor(borderGrey.r, borderGrey.g, borderGrey.b);
          doc.setLineWidth(0.5);
          doc.line(margin + 5, y - 2, margin + 5, y + 12);
          
          // Small timing badge
          doc.setFillColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
          doc.circle(margin + 5, y + 1, 1, 'F');

          // Timing text
          doc.setFont('helvetica', 'bold');
          doc.setFontSize(8.5);
          doc.setTextColor(scandiBlue.r, scandiBlue.g, scandiBlue.b);
          doc.text(act.time || 'Activity', margin + 9, y + 1.5);

          // Location (optional)
          if (act.location) {
            doc.setFont('helvetica', 'normal');
            doc.setFontSize(8);
            doc.setTextColor(slateMuted.r, slateMuted.g, slateMuted.b);
            const locText = ` @ ${act.location}`;
            doc.text(sanitizeText(locText, language), margin + 9 + doc.getTextWidth(act.time || 'Activity') + 2, y + 1.5);
          }

          // Activity Title
          doc.setFont('helvetica', 'bold');
          doc.setFontSize(10);
          doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
          doc.text(sanitizeText(act.title, language), margin + 9, y + 6);
          
          y += 9.5;

          // Activity Description
          if (act.description) {
            // Indent the wrapped text for activities slightly to keep clean grid look
            const actLines = doc.splitTextToSize(sanitizeText(act.description, language), contentW - 12);
            doc.setFont('helvetica', 'normal');
            doc.setFontSize(9);
            doc.setTextColor(darkCharcoal.r, darkCharcoal.g, darkCharcoal.b);
            const actLineH = 9 * 0.3527 * 1.3;
            
            for (const line of actLines) {
              if (y + actLineH > pageH - 18) {
                doc.addPage();
                drawPageBorder();
                y = 20;
              }
              doc.text(line, margin + 9, y);
              y += actLineH;
            }
          }

          // Cost (optional)
          if (act.cost) {
            ensureSpace(5);
            doc.setFont('helvetica', 'bold');
            doc.setFontSize(8);
            doc.setTextColor(22, 163, 74); // Green
            doc.text(`${language === 'ar' ? 'التكلفة المقدرة: ' : language === 'sv' ? 'Beräknad kostnad: ' : 'Est. Cost: '} ${act.cost}`, margin + 9, y);
            y += 4;
          }

          y += 3.5; // padding between activities
        }
      }
      y += 5; // space between days
    }
  }

  // --- FINISH: ADD PAGE NUMBERS TO FOOTERS ---
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    drawFooter(i, totalPages);
  }

  // Save the PDF locally in user's browser
  const fileName = `${data.title ? data.title.toLowerCase().replace(/[^a-z0-9]+/g, '_') : 'sweden_itinerary'}.pdf`;
  doc.save(fileName);
}
